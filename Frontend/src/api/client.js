// All backend calls live here. Vercel rewrites /api/* to the Render backend (see vercel.json).
const BASE = '/api';

// FastAPI returns errors as { detail: "text" } or, for validation errors, { detail: [{ msg, loc }] }
function errorMessage(status, body) {
  const detail = body?.detail;
  if (typeof detail === 'string') return detail;
  if (Array.isArray(detail) && detail.length) {
    return detail.map((d) => `${d.loc?.at(-1) ?? 'value'}: ${d.msg}`).join('; ');
  }
  return `Request failed (${status})`;
}

async function request(path, options = {}) {
  let res;
  try {
    res = await fetch(`${BASE}${path}`, {
      headers: { 'Content-Type': 'application/json' },
      credentials: 'include', // send the session cookie set by /auth/login
      ...options,
    });
  } catch {
    throw new Error('Cannot reach the server. Is the backend running?');
  }

  const body = await res.json().catch(() => null);

  if (!res.ok) throw new Error(errorMessage(res.status, body));

  return body;
}

// Sends multipart form data (file uploads). No JSON header here, so the browser
// sets the multipart Content-Type with its boundary.
async function uploadForm(path, fields) {
  const form = new FormData();
  for (const [key, value] of Object.entries(fields)) {
    form.append(key, value);
  }

  let res;
  try {
    res = await fetch(`${BASE}${path}`, {
      method: 'POST',
      body: form,
      credentials: 'include',
    });
  } catch {
    throw new Error('Cannot reach the server. Is the backend running?');
  }

  const body = await res.json().catch(() => null);

  if (!res.ok) throw new Error(errorMessage(res.status, body));

  return body;
}

export const api = {
  // Email + password. The backend sets a session cookie and returns the admin account.
  login: (email, password) =>
    request('/auth/login', { method: 'POST', body: JSON.stringify({ email, password }) }),

  // Creates an admin account from name, email and password.
  register: ({ name, email, password }) =>
    request('/auth/register', { method: 'POST', body: JSON.stringify({ name, email, password }) }),

  // Returns the signed-in admin, or throws 401 when there is no session cookie.
  me: () => request('/auth/me'),

  logout: () => request('/auth/logout', { method: 'POST' }),

  // TODO: the backend has no /auth/google route yet.
  googleLogin: (credential) =>
    request('/auth/google', { method: 'POST', body: JSON.stringify({ credential }) }),

  // One restaurant by ID. No sign-in needed. Used by the public page a QR code opens.
  getRestaurant: (id) => request(`/restaurants/${encodeURIComponent(id)}`),

  // Public list of all restaurants.
  // Trailing slash matters: FastAPI redirects /restaurants to /restaurants/, and that redirect breaks on Vercel.
  listRestaurants: () => request('/restaurants/'),

  // Only the signed-in owner's restaurants.
  listMyRestaurants: () => request('/restaurants/mine'),

  // The QR image generated by the backend. Use it as an <img> src.
  restaurantQrUrl: (id) => `${BASE}/restaurants/${encodeURIComponent(id)}/qr`,

  // Body: { name, location, ... }.
  createRestaurant: (data) =>
    request('/restaurants/', { method: 'POST', body: JSON.stringify(data) }),

  // Body: any subset of the restaurant fields, in snake_case.
  updateRestaurant: (id, data) =>
    request(`/restaurants/${encodeURIComponent(id)}`, { method: 'PUT', body: JSON.stringify(data) }),

  deleteRestaurant: (id) =>
    request(`/restaurants/${encodeURIComponent(id)}`, { method: 'DELETE' }),

  // Photos for one restaurant (public).
  listRestaurantPhotos: (id) => request(`/restaurants/${encodeURIComponent(id)}/photos`),

  // Uploads one image from the device gallery. category: main | interior | exterior | food.
  uploadRestaurantPhoto: (id, category, file) =>
    uploadForm(`/restaurants/${encodeURIComponent(id)}/photos`, { category, photo: file }),

  // Removes one photo by its ID.
  deletePhoto: (photoId) =>
    request(`/photos/${encodeURIComponent(photoId)}`, { method: 'DELETE' }),
};